    """Mark a repository-owned public rule after its metadata header is assembled.

    Callers must use reviewed constants, not text selected by a user-provided ID,
    a tool result, a document's self-description, or a model response.
    """
    if not isinstance(text, str):
        raise TypeError("public rule must be text")
