CREATE TABLE IF NOT EXISTS microsoft_binding_migration_wsu_aishop6 (
    resource_id BIGINT UNSIGNED PRIMARY KEY,
    email VARCHAR(255) NOT NULL,
    owner_id BIGINT UNSIGNED NOT NULL,
    source_address VARCHAR(320) NOT NULL,
    binding_id BIGINT UNSIGNED NOT NULL,
    binding_updated_at DATETIME(3) NOT NULL,
    original_status VARCHAR(32) NOT NULL,
    resource_version BIGINT UNSIGNED NOT NULL DEFAULT 0,
    generation BIGINT UNSIGNED NOT NULL DEFAULT 0,
    credential_revision BIGINT UNSIGNED NOT NULL DEFAULT 0,
    credential_digest VARCHAR(64) NOT NULL DEFAULT '',
    resolved_source VARCHAR(320) NOT NULL DEFAULT '',
    target_address VARCHAR(320) NOT NULL DEFAULT '',
    batch_id VARCHAR(64) NOT NULL DEFAULT '',
    state VARCHAR(32) NOT NULL DEFAULT 'queued',
    phase VARCHAR(64) NOT NULL DEFAULT '',
    attempts INT NOT NULL DEFAULT 0,
    retry_count INT UNSIGNED NOT NULL DEFAULT 0,
    retry_at DATETIME(3) NULL,
    safe_error VARCHAR(500) NOT NULL DEFAULT '',
    created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    INDEX migration_state_resource (state,resource_id),
    INDEX migration_batch (batch_id),
    reserved_target VARCHAR(320) GENERATED ALWAYS AS (NULLIF(target_address,'')) STORED,
    UNIQUE INDEX migration_target (reserved_target)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci
